    fun init(context: Context) {
        store = context.applicationContext.getSharedPreferences(PREF, Context.MODE_PRIVATE)
    }

    /**
     * 覆盖某个动作的候选文案。
     * 入口：MainActivity 的「自定义文案」里以 JSON 传入，形如
     * {"FERTILIZE_TEXTS":["一键施肥","全部施用"]}
     * 这样改版时无需动代码。
     */
    fun overrideFromJson(json: String) {
        try {
            val obj = org.json.JSONObject(json)
            val editor = store?.edit() ?: return
            val keys = obj.keys()
            while (keys.hasNext()) {
                val key = keys.next()
                val arr = obj.getJSONArray(key)
                val list = ArrayList<String>()
                for (i in 0 until arr.length()) {
                    list.add(arr.getString(i))
                }
                editor.putString(key, org.json.JSONArray(list).toString())
            }
            editor.apply()
            Log.i(TAG, "选择器覆盖成功")
            reload()
        } catch (e: Exception) {
            Log.e(TAG, "选择器覆盖解析失败: ${e.message}")
        }
    }

