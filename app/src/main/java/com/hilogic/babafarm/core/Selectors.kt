        val sp = store ?: return
        fun load(key: String, def: List<String>): List<String> {
            val raw = sp.getString(key, null) ?: return def
            return try {
                val arr = org.json.JSONArray(raw)
                (0 until arr.length()).map { arr.getString(it) }
            } catch (e: Exception) {
                def
            }
        }
        FERTILIZE_TEXTS = load("FERTILIZE_TEXTS", FERTILIZE_TEXTS)
        SHAKE_TEXTS = load("SHAKE_TEXTS", SHAKE_TEXTS)
